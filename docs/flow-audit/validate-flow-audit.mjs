import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
if (!process.argv.includes('--historical')) {
  await import('./validate-current-audit.mjs');
  process.exit(0);
}
const here=path.dirname(fileURLToPath(import.meta.url));
const read=n=>fs.readFileSync(path.join(here,n),'utf8');
const data=JSON.parse(read('2026-10-02-connection-map.json'));
const raw=JSON.parse(read('2026-10-02-screen-reactions.json'));
const inventory=JSON.parse(read('2026-10-02-screen-inventory.json'));
const html=read('2026-10-02-index.html');
new vm.Script(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
const embedded=JSON.parse(html.match(/<script type="application\/json" id="data">([\s\S]*?)<\/script>/)[1]);
assert.equal(embedded.records.length,inventory.length);
assert.equal(embedded.edges.length,data.edges.length);
assert.equal(new Set(inventory.map(s=>s.id)).size,inventory.length);
assert.equal(data.records.filter(s=>s.controls!==null).length,raw.length);
assert(data.records.filter(s=>s.evidence==='REACTIONS_CAPTURED').every(s=>raw.some(r=>r.id===s.id)));
assert(data.edges.every(e=>raw.some(s=>s.id===e.source)));
assert(data.edges.every(e=>e.destinationCaptured===inventory.some(s=>s.id===e.to)));
const page=fs.readFileSync(path.join(here,'../APP_FLOW_MAP.md'),'utf8');
const ids=[...new Set(page.match(/\b\d{1,5}:\d{1,6}\b/g))];
const known=new Set([...inventory.map(s=>s.id),...data.referencedOutsideInventory.map(s=>s.id),'955:4752','985:4904','1052:5011']);
const missing=ids.filter(id=>!known.has(id));
assert.deepEqual(missing,[],`Document IDs not supported by captured inventory/references: ${missing.join(', ')}`);
